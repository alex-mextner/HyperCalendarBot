// ─── rule pages ─────────────────────────────────────────────────────────────

export const RULES_DIRECTORY = 'rules';
/** Rendered lines of rule cards per page; keeps every page far below the 1200-line file ceiling. */
const PAGE_CARD_LINES = 1000;
/** Lines the `---` divider between two cards adds (blank, rule, blank). */
const CARD_SEPARATOR_LINES = 3;

interface RuleCard {
  entry: CatalogueEntry;
  text: string;
  lines: number;
}

export interface RulePage {
  /** Path relative to docs/intents. */
  file: string;
  category: string;
  title: string;
  part: number;
  parts: number;
  cards: RuleCard[];
}

/** Greedy, order-preserving split so a long category continues on a further page instead of overflowing one. */
function packCards(cards: RuleCard[]): RuleCard[][] {
  const pages: RuleCard[][] = [];
  let used = 0;
  for (const card of cards) {
    const page = pages.at(-1);
    const cost = card.lines + CARD_SEPARATOR_LINES;
    if (page && used + cost <= PAGE_CARD_LINES) {
      page.push(card);
      used += cost;
      continue;
    }
    if (card.lines > PAGE_CARD_LINES)
      throw new Error(`Rule ${card.entry.name} renders ${card.lines} lines, more than one page holds`);
    pages.push([card]);
    used = card.lines;
  }
  return pages;
}

const categorySlug = (category: string): string => category.toLowerCase().replace(/[^a-z0-9_-]+/g, '-');

function assertDistinctFiles(pages: readonly RulePage[]): void {
  const files = pages.map((page) => page.file);
  if (new Set(files).size !== files.length) throw new Error('Two rule pages would write the same file');
}

export function planRulePages(c: Catalogue): RulePage[] {
  const pages = groupByCategory(c.entries).flatMap((group) => {
    const cards = group.entries.map((entry) => {
      const text = renderRuleMarkdown(entry);
      return { entry, text, lines: lineCount(text) };
    });
    const shards = packCards(cards);
    return shards.map((shard, index) => ({
      file: `${RULES_DIRECTORY}/${categorySlug(group.category)}${shards.length > 1 ? `-${index + 1}` : ''}.md`,
      category: group.category,
      title: categoryTitle(group.category),
      part: index + 1,
      parts: shards.length,
      cards: shard,
    }));
  });
  assertDistinctFiles(pages);
  return pages;
}

/** Rule name to the page that carries its card. */
export function ruleFiles(pages: readonly RulePage[]): Map<string, string> {
  return new Map(pages.flatMap((page) => page.cards.map((card) => [card.entry.name, page.file] as const)));
}

const pageHeading = (page: RulePage): string =>
  page.parts > 1 ? `${page.title} (часть ${page.part} из ${page.parts})` : page.title;

const siblingFile = (page: RulePage): string => page.file.slice(RULES_DIRECTORY.length + 1);

function renderRulePage(c: Catalogue, pages: readonly RulePage[], index: number): string {
  const page = pages[index]!;
  const previous = pages[index - 1];
  const next = pages[index + 1];
  const navigation = [
    previous ? `[← ${escapeMarkdown(pageHeading(previous))}](${siblingFile(previous)})` : '',
    '[Каталог правил](../README.md)',
    next ? `[${escapeMarkdown(pageHeading(next))} →](${siblingFile(next)})` : '',
    '[Как читать описание шагов](../README.md#как-читать-описание-шагов)',
    '[Описание движка](../engine.md)',
  ]
    .filter(Boolean)
    .join(' · ');
  return `${[
    GENERATED_MARKER,
    `# ${escapeMarkdown(pageHeading(page))}`,
    navigation,
    `Отпечаток целевого сида: \`${c.fingerprint}\``,
    page.cards.map((card) => card.text).join('\n\n---\n\n'),
  ].join('\n\n')}\n`;
}

function renderCategoryIndex(c: Catalogue, pages: readonly RulePage[]): string {
  const items = groupByCategory(c.entries).map((group) => {
    const own = pages.filter((page) => page.category === group.category);
    const title = escapeMarkdown(categoryTitle(group.category));
    const count = `правил: ${group.entries.length}`;
    if (own.length === 1) return `- [${title}](${own[0]!.file}) — ${count}`;
    const parts = own.map((page) => `[часть ${page.part}](${page.file})`).join(' · ');
    return `- ${title} — ${count}; ${parts}`;
  });
  return `## Правила по категориям\n\nКарточки правил лежат на отдельных страницах: у каждой категории своя, длинные категории продолжаются на следующей странице.\n\n${items.join('\n')}`;
}

/** The README entry page: everything except the rule cards themselves. */
export function renderMarkdown(c: Catalogue, pages: readonly RulePage[] = planRulePages(c)): string {
  const files = ruleFiles(pages);
  return `${[
    GENERATED_MARKER,
    renderIntroduction(c),
    `## Сводка\n\n${renderCounts(c)}`,
    renderLineageSummaryLine(c),
    HOW_TO,
    renderGlossary(),
    `## Все правила\n\n${renderIndexTable(c, files)}`,
    renderCategoryIndex(c, pages),
    renderLineageSection(c, files),
  ].join('\n\n')}\n`;
}

/** README.md plus every rule page, keyed by path relative to docs/intents. */
export function renderMarkdownFiles(c: Catalogue): { [file: string]: string } {
  const pages = planRulePages(c);
  const files: { [file: string]: string } = { 'README.md': renderMarkdown(c, pages) };
  pages.forEach((page, index) => {
    files[page.file] = renderRulePage(c, pages, index);
  });
  return files;
}
